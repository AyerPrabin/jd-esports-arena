def _lev(a, b, mx):
    if abs(len(a) - len(b)) > mx:
        return mx + 1
    prev = list(range(len(b) + 1))
    for i, ca in enumerate(a, 1):
        cur = [i]
        mn = i
        for j, cb in enumerate(b, 1):
            v = min(prev[j] + 1, cur[j - 1] + 1, prev[j - 1] + (0 if ca == cb else 1))
            cur.append(v)
            if v < mn:
                mn = v
        if mn > mx:
            return mx + 1
        prev = cur
    return prev[-1]


def _fix_word(mw):
    w = mw.group(0)
    lw = w.lower()
    if lw in _VOCAB:
        return w
    best, bd = None, 3
    for v in _VOCAB:
        if abs(len(v) - len(lw)) > 2:
            continue
        d = _lev(lw, v, 2)
        if d < bd:
            bd, best = d, v
            if d == 1:
                break
    if best and ((bd == 1 and len(lw) >= 4) or (bd == 2 and len(lw) >= 7)):
        return best
    return w


def _correct(s):
    return re.sub(r"[a-zA-Z]{4,}", _fix_word, s)


@functools.lru_cache(maxsize=512)
def _lookup(s):
    s = _correct(s)  # fix typos against the vocabulary first
    cand, seen = [], set()
    for t in s.split():
        for e in _INDEX.get(t, ()):
            i = id(e)
            if i not in seen:
                seen.add(i)
                cand.append(e)
    pool = cand if cand else [e for v in KB.values() for e in v]
    best, bs = None, 0
    for e in pool:
        sc = _score(e["k"], s)
        if sc > bs:
            bs, best = sc, e
    if bs < 2 and cand:
        for e in (e for v in KB.values() for e in v):
            sc = _score(e["k"], s)
            if sc > bs:
                bs, best = sc, e
    return (best["a"] if best and bs >= 2 else None)


