@functools.lru_cache(maxsize=512)
def _search(s, k, min_score):
    """Top-k relevant entries (answers) for grounding. Same index + scoring as _lookup."""
    s = _correct(s)
    cand, seen = [], set()
    for t in s.split():
        for e in _INDEX.get(t, ()):
            i = id(e)
            if i not in seen:
                seen.add(i)
                cand.append(e)
    scored = []
    for e in cand:
        sc = _score(e["k"], s)
        if sc >= min_score:
            scored.append((sc, e))
    scored.sort(key=lambda x: x[0], reverse=True)
    return tuple(e["a"] for _sc, e in scored[:k])


def knowledge_search(query, k=3, min_score=3, founder="Prabin"):
    """Return up to k curated facts relevant to the query, for grounding the model (RAG)."""
    hits = _search((query or "").lower(), k, min_score)
    return [h.replace("{name}", founder) for h in hits]


